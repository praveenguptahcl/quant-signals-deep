def test_cost_interface_record():
    """§R5 record: every regime state maps to a complete, sane adjustment."""
    rec = COST_ADJUSTMENT_R048
    assert rec["regime_id"] == "R048"
    assert rec["version"] == "1.1.0"
    assert rec["tag"] == "[example]"
    for st in ("FEAR", "NORMAL", "COMPLACENCY"):
        adj = rec[st]
        for k in ("spread_mult", "impact_mult", "borrow_mult"):
            assert adj[k] > 0, (st, k, adj[k])
        assert adj["fee_add_bps"] >= 0
    # FEAR must widen costs vs NORMAL; NORMAL is the identity record
    assert rec["FEAR"]["spread_mult"] >= rec["NORMAL"]["spread_mult"]
    assert rec["FEAR"]["impact_mult"] >= rec["NORMAL"]["impact_mult"]
    assert rec["NORMAL"]["spread_mult"] == 1.0
    assert rec["NORMAL"]["impact_mult"] == 1.0
