def test_f3_dual_estimator_agreement():
    """Recomputed ratio from raw put/call legs must agree with the published print."""
    tape = _load("R048_tape_hysteresis.csv")
    n = 0
    for e in tape:
        try:
            v1 = _row_value(e, CFG)
            v2 = _dual_value(e, CFG)
        except ValueError:
            continue  # F1/F2 row or no raw legs: nothing to check
        if not (0.0 < v1 < CFG["bounds_hi"]):
            continue  # F2 row: both estimators must agree on UNKNOWN-ness
        assert _close(v1, v2, DUAL_TOL), (v1, v2)
        n += 1
    assert n >= 10, f"dual estimator checked too few rows: {n}"


def test_f4_staleness_expires_to_unknown():
    tape = _load("R048_tape.csv")
    rs = detect(None, tape, CFG)[-1]
    assert rs["computed_at"] > 0
    aged = apply_freshness(rs, rs["computed_at"] + (CFG["stale_days"] + 1) * CADENCE_NS)
    assert aged["module_state"] == "UNKNOWN"
    assert aged["state"] == "UNKNOWN"
    fresh = apply_freshness(rs, rs["computed_at"] + CADENCE_NS)
    assert fresh["module_state"] == rs["module_state"]


